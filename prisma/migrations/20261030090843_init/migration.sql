-- Full-text search over the catalogue.
CREATE OR REPLACE FUNCTION product_search_document(name text, description text, tags text[])
RETURNS tsvector AS $$
  SELECT setweight(to_tsvector('english'::regconfig, coalesce(name, '')), 'A')
      || setweight(to_tsvector('english'::regconfig, coalesce(array_to_string(tags, ' '), '')), 'B')
      || setweight(to_tsvector('english'::regconfig, coalesce(description, '')), 'C');
$$ LANGUAGE sql IMMUTABLE PARALLEL SAFE;

CREATE INDEX product_search_idx ON "Product" USING GIN (product_search_document("name", "description", "tags"));
